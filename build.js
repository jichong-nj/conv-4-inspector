// Build src/client.js into the module-loader bundle the host serves at
// /plugins/<id>/client.js. No bundler dependency: the authored source is
// already plain ES2020 + React.createElement, so the wrapper only supplies the
// CommonJS-ish `require` / `module` / `exports` seam the loader expects.
//
//   node build.js

import { mkdir, readFile, writeFile } from "node:fs/promises";

const ROOT = new URL(".", import.meta.url);
// The module id the browser loader looks for is the *package name*, so read it
// from package.json instead of hardcoding it: renaming the package then only
// touches package.json. A mismatch surfaces client-side as
// `client-modules: could not load "<name>/client.js": loaded without registering
// "<name>" via __ModuleLoader__.load`.
const { name: ID } = JSON.parse(
	await readFile(new URL("package.json", ROOT), "utf8"),
);

const source = await readFile(new URL("src/client.js", ROOT), "utf8");
const indented = source
	.replace(/\s+$/, "")
	.split("\n")
	.map((line) => (line.length > 0 ? `\t\t${line}` : ""))
	.join("\n");

const bundle = `// GENERATED by build.js from src/client.js — do not edit.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indented}
		return module.exports;
	}
});
`;

await mkdir(new URL("lib/", ROOT), { recursive: true });
await writeFile(new URL("lib/client.js", ROOT), bundle, "utf8");
console.log(`built lib/client.js (${bundle.length} bytes)`);
